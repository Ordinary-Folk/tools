#!/usr/bin/env node
// Builds library.js (the data behind tools.ordinary.co/look/icons and the icon
// maker) from house.json. Run after any change to house.json or custom/:
//   node look/icons/build-library.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readIcon, house } from './gen.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const out = {};
for (const [name, entry] of Object.entries(house())) {
  const icon = readIcon('@' + name);
  const [base, style] = entry.icon.split(':');
  const custom = entry.icon.endsWith('.svg');
  // Solid unless :outline, but some icons only exist as outline (readIcon falls back).
  const drawn = custom ? 'custom' : icon.style === 'solid' ? 'solid' : 'outline';
  out[name] = { d: icon.d, eo: icon.evenOdd || undefined, source: custom ? entry.icon : base, style: drawn, apps: entry.apps, note: entry.note };
}
const js = `// GENERATED by look/icons/build-library.mjs from house.json. Do not edit.\nwindow.OF_ICONS = ${JSON.stringify(out)};\n`;
fs.writeFileSync(path.join(HERE, 'library.js'), js);
console.log(`library.js: ${Object.keys(out).length} icons`);
